private void initTableSach() {
    modelSach = new DefaultTableModel();
    modelSach.setColumnIdentifiers(new String[]{"Mã Sách", "Tên Sách", "Tác Giả", "Thể Loại", "Số Lượng"});
    tblSach.setModel(modelSach);
}

private void loadDataToTableSach() {
    if (conn == null) return;
    modelSach.setRowCount(0);
    String sql = "SELECT * FROM Sach ORDER BY MaSach";

    try (Statement stmt = conn.createStatement();
         ResultSet rs = stmt.executeQuery(sql)) {
        while (rs.next()) {
            Vector<Object> row = new Vector<>();
            row.add(rs.getString("MaSach"));
            row.add(rs.getString("TenSach"));
            row.add(rs.getString("TacGia"));
            row.add(rs.getString("TheLoai"));
            row.add(rs.getInt("SoLuong"));
            modelSach.addRow(row);
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Lỗi tải dữ liệu Sách: " + e.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
}

private void resetFormSach() {
    txtMaSach.setText("");
    txtTenSach.setText("");
    txtTacGia.setText("");
    txtTheLoai.setText("");
    txtSoLuong.setText("");
    txtMaSach.setEditable(true);
    tblSach.clearSelection();
}

private void addTableSachListener() {
    tblSach.getSelectionModel().addListSelectionListener((ListSelectionEvent e) -> {
        if (!e.getValueIsAdjusting() && tblSach.getSelectedRow() != -1) {
            int row = tblSach.getSelectedRow();
            txtMaSach.setText(modelSach.getValueAt(row, 0).toString());
            txtTenSach.setText(modelSach.getValueAt(row, 1).toString());
            txtTacGia.setText(modelSach.getValueAt(row, 2) != null ? modelSach.getValueAt(row, 2).toString() : "");
            txtTheLoai.setText(modelSach.getValueAt(row, 3) != null ? modelSach.getValueAt(row, 3).toString() : "");
            txtSoLuong.setText(modelSach.getValueAt(row, 4).toString());
            txtMaSach.setEditable(false);
        }
    });
}
 

