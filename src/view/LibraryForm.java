    private void btnThemSachActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemSachActionPerformed
        if (conn == null) {
            JOptionPane.showMessageDialog(this, "Chưa kết nối CSDL!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String maSach = txtMaSach.getText().trim();
        String tenSach = txtTenSach.getText().trim();
        String tacGia = txtTacGia.getText().trim();
        String theLoai = txtTheLoai.getText().trim();

        if (maSach.isEmpty() || tenSach.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mã sách và Tên sách không được để trống!", "Lỗi", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int soLuong;
        try {
            String soLuongText = txtSoLuong.getText().trim();
             if (soLuongText.isEmpty()) {
                soLuong = 0;
            } else {
                soLuong = Integer.parseInt(soLuongText);
                 if (soLuong < 0) {
                     JOptionPane.showMessageDialog(this, "Số lượng không được âm!", "Lỗi", JOptionPane.WARNING_MESSAGE);
                     return;
                 }
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Số lượng phải là một số nguyên!", "Lỗi", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String sql = "INSERT INTO Sach(MaSach, TenSach, TacGia, TheLoai, SoLuong) VALUES(?, ?, ?, ?, ?)";

        try (PreparedStatement pstmt = conn.prepareStatement(sql)) {
            pstmt.setString(1, maSach);
            pstmt.setString(2, tenSach);
            pstmt.setString(3, tacGia);
            pstmt.setString(4, theLoai);
            pstmt.setInt(5, soLuong);

            int affectedRows = pstmt.executeUpdate();
            if (affectedRows > 0) {
                JOptionPane.showMessageDialog(this, "Thêm sách thành công!");
                loadDataToTableSach();
                resetFormSach();
            }
        } catch (SQLException e) {
            if (e.getSQLState().equals("23505")) {
                JOptionPane.showMessageDialog(this, "Mã sách đã tồn tại.", "Lỗi", JOptionPane.ERROR_MESSAGE);
            } else {
                 JOptionPane.showMessageDialog(this, "Lỗi khi thêm sách: " + e.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
                 e.printStackTrace();
            }
        } catch (NullPointerException e) {
             JOptionPane.showMessageDialog(this, "Lỗi kết nối CSDL khi thêm. Vui lòng kiểm tra lại.", "Lỗi Kết Nối", JOptionPane.ERROR_MESSAGE);
             e.printStackTrace();
        }
    }//GEN-LAST:event_btnThemSachActionPerformed

    private void btnSuaSachActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaSachActionPerformed
        if (conn == null) {
            JOptionPane.showMessageDialog(this, "Chưa kết nối CSDL!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String maSach = txtMaSach.getText().trim();
        if (maSach.isEmpty() || txtMaSach.isEditable()) {
            JOptionPane.showMessageDialog(this, "Bạn phải chọn một cuốn sách từ bảng để cập nhật.", "Lỗi", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String tenSach = txtTenSach.getText().trim();
        String tacGia = txtTacGia.getText().trim();
        String theLoai = txtTheLoai.getText().trim();
        int soLuong;

        try {
            String soLuongText = txtSoLuong.getText().trim();
             if (soLuongText.isEmpty()) {
                soLuong = 0;
            } else {
                soLuong = Integer.parseInt(soLuongText);
                 if (soLuong < 0) {
                     JOptionPane.showMessageDialog(this, "Số lượng không được âm!", "Lỗi", JOptionPane.WARNING_MESSAGE);
                     return;
                 }
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Số lượng phải là một số nguyên!", "Lỗi", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String sql = "UPDATE Sach SET TenSach = ?, TacGia = ?, TheLoai = ?, SoLuong = ? WHERE MaSach = ?";

        try (PreparedStatement pstmt = conn.prepareStatement(sql)) {
            pstmt.setString(1, tenSach);
            pstmt.setString(2, tacGia);
            pstmt.setString(3, theLoai);
            pstmt.setInt(4, soLuong);
            pstmt.setString(5, maSach);

            int affectedRows = pstmt.executeUpdate();
            if (affectedRows > 0) {
                JOptionPane.showMessageDialog(this, "Cập nhật thành công!");
                loadDataToTableSach();
                resetFormSach();
            } else {
                JOptionPane.showMessageDialog(this, "Không tìm thấy sách để cập nhật (có thể đã bị xóa).", "Thông báo", JOptionPane.INFORMATION_MESSAGE);
                 resetFormSach();
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Lỗi khi cập nhật sách: " + e.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        } catch (NullPointerException e) {
             JOptionPane.showMessageDialog(this, "Lỗi kết nối CSDL khi cập nhật. Vui lòng kiểm tra lại.", "Lỗi Kết Nối", JOptionPane.ERROR_MESSAGE);
             e.printStackTrace();
        }
    }//GEN-LAST:event_btnSuaSachActionPerformed

    private void btnXoaSachActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaSachActionPerformed
        if (conn == null) {
            JOptionPane.showMessageDialog(this, "Chưa kết nối CSDL!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String maSach = txtMaSach.getText().trim();
         if (maSach.isEmpty() || txtMaSach.isEditable()) {
            JOptionPane.showMessageDialog(this, "Bạn phải chọn một cuốn sách từ bảng để xoá.", "Lỗi", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Bạn có chắc chắn muốn xoá sách '" + maSach + "' không?",
                "Xác nhận xoá",
                JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM Sach WHERE MaSach = ?";

        try (PreparedStatement pstmt = conn.prepareStatement(sql)) {
            pstmt.setString(1, maSach);

            int affectedRows = pstmt.executeUpdate();
            if (affectedRows > 0) {
                JOptionPane.showMessageDialog(this, "Xoá sách thành công!");
                loadDataToTableSach();
                resetFormSach();
            } else {
                 JOptionPane.showMessageDialog(this, "Không tìm thấy sách để xoá (có thể đã bị xóa trước đó).", "Thông báo", JOptionPane.INFORMATION_MESSAGE);
                 resetFormSach();
            }
        } catch (SQLException e) {
            if (e.getSQLState().equals("23503")) {
                 JOptionPane.showMessageDialog(this, "Không thể xoá sách này! Sách đang được độc giả mượn.", "Lỗi Ràng Buộc", JOptionPane.ERROR_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Lỗi khi xoá sách: " + e.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
                 e.printStackTrace();
            }
        } catch (NullPointerException e) {
             JOptionPane.showMessageDialog(this, "Lỗi kết nối CSDL khi xóa. Vui lòng kiểm tra lại.", "Lỗi Kết Nối", JOptionPane.ERROR_MESSAGE);
             e.printStackTrace();
        }
    }//GEN-LAST:event_btnXoaSachActionPerformed

